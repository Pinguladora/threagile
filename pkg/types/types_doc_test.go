// defaultTechnologies reads the built-in technologies only.
type defaultTechnologies struct{ appFolder string }

func (what defaultTechnologies) GetAppFolder() string          { return what.appFolder }
func (what defaultTechnologies) GetTechnologyFilename() string { return "" }

// TestTypesDocMatchesTypes keeps docs/types.md in line with the built-in types.
func TestTypesDocMatchesTypes(t *testing.T) {
	got := typesDoc(t, GetBuiltinTypeValues(defaultTechnologies{appFolder: t.TempDir()}))
	if *updateDocs {
		require.NoError(t, os.WriteFile(typesDocFile, []byte(got), 0o600))
		return
	}
	want, err := os.ReadFile(typesDocFile)
	require.NoError(t, err)
	assert.Equal(t, string(want), got, "docs/types.md is out of date, run the test with -update")
}

// typesDoc renders the values of the built-in types as Markdown tables, one section per type.
func typesDoc(t *testing.T, types map[string][]TypeEnum) string {
	t.Helper()
	var doc strings.Builder
	doc.WriteString("# Types\n\n")
	doc.WriteString("The values the fields of a model take. `threagile list-types` prints the same, " +
		"including the technologies of a `--technology` file. This file is generated by " +
		"`go test ./pkg/types -update`.\n")
	for _, name := range slices.Sorted(maps.Keys(types)) {
		field, ok := typeFields[name]
		require.True(t, ok, "no field documented for type %q", name)
		doc.WriteString("\n## " + name + "\n\nUsed by " + field + ".\n\n")
		if name == "Technical Asset Technology" {
			writeTechnologyTable(t, &doc, types[name])
			continue
		}
		doc.WriteString("| Value | Description |\n|-------|-------------|\n")
		for _, value := range types[name] {
			doc.WriteString("| `" + value.String() + "` | " + tableCell(value.Explain()) + " |\n")
		}
	}
	return doc.String()
}

// writeTechnologyTable renders the technologies with their aliases, which models may use instead of the names.
func writeTechnologyTable(t *testing.T, doc *strings.Builder, technologies []TypeEnum) {
	t.Helper()
	doc.WriteString("| Value | Aliases | Description |\n|-------|---------|-------------|\n")
	for _, value := range technologies {
		technology, ok := value.(Technology)
		require.True(t, ok, "technology %q is a %T", value.String(), value)
		aliases := make([]string, 0, len(technology.Aliases))
		for _, alias := range technology.Aliases {
			aliases = append(aliases, "`"+alias+"`")
		}
		doc.WriteString("| `" + technology.Name + "` | " + strings.Join(aliases, ", ") + " | " +
			tableCell(technology.Description) + " |\n")
	}
}

// tableCell makes the text fit into a cell of a Markdown table.
func tableCell(text string) string {
	return strings.ReplaceAll(strings.Join(strings.Fields(text), " "), "|", `\|`)
}
