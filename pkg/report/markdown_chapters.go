func (what *markdownWriter) questions(view *reportView) {
	what.paragraph(strong(strconv.Itoa(view.UnansweredQuestions) + " of " + strconv.Itoa(len(view.Questions)) +
		" unanswered"))
	what.paragraph("This chapter lists custom questions that arose during the threat modeling process.")
	entries := make([]markdownEntry, 0, len(view.Questions))
	for _, question := range view.Questions {
		answer := question.Answer
		if !question.Answered {
			answer = "<i>answer pending</i>" // threagile's markup for the note, as HTML shows it muted
		}
		entries = append(entries, markdownEntry{strong(markdownText(question.Question)), answer})
	}
	what.entries(entries...)
}

