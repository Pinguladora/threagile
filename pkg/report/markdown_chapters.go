// report writes the whole report: the title, the contents, the chapters and when it was generated.
func (what *markdownWriter) report(view *reportView) {
	what.titlePage(view)
	what.heading(2, "", "Contents")
	items := make([]string, 0, len(view.Sections))
	for index, section := range view.Sections {
		items = append(items, strconv.Itoa(index+1)+". "+what.linked(markdownText(section.Title), section.ID))
	}
	what.block(items...)

	for _, section := range view.Sections {
		what.heading(2, section.ID, section.Title)
		markdownChapters[section.ID](what, view)
	}
	what.paragraph(muted("Generated by Threagile " + markdownText(view.Run.ThreagileVersion) + " on " +
		markdownText(view.Generated) + "."))
}

func (what *markdownWriter) titlePage(view *reportView) {
	what.heading(1, "", "Threat Model Report: "+view.Title)
	lines := []string{"- " + strong("Author:") + " " + markdownAuthor(view.Author)}
	if len(view.Contributors) > 0 {
		lines = append(lines, "- "+strong("Contributors:"))
		for _, contributor := range view.Contributors {
			lines = append(lines, "    - "+markdownBlockStart(markdownAuthor(contributor)))
		}
	}
	lines = append(lines,
		"- "+strong("Date:")+" "+markdownText(view.Date),
		"- "+strong("Business criticality:")+" "+markdownText(view.Model.BusinessCriticality.String()),
		"- "+strong("Threagile version:")+" "+markdownText(view.Run.ThreagileVersion),
	)
	what.block(lines...)
}

func markdownAuthor(author viewAuthor) string {
	text := markdownText(author.Name)
	if author.Contact != "" {
		text += " (" + markdownText(author.Contact) + ")"
	}
	if author.Homepage != "" {
		text += ", " + markdownLink(markdownText(author.Homepage), markdownURL(author.Homepage))
	}
	return text
}

// muted is inline Markdown in italics, for the notes that the HTML report shows muted.
func muted(text string) string {
	if text == "" {
		return ""
	}
	return "_" + text + "_"
}

func (what *markdownWriter) managementSummary(view *reportView) {
	what.paragraph("Threagile toolkit was used to model the architecture of " + quoted(view.Title) + " and derive " +
		"risks by analyzing the components and data flows. The risks identified during this analysis are shown in the " +
		"following chapters. Identified risks during threat modeling do not necessarily mean that the vulnerability " +
		"associated with this risk actually exists: it is more to be seen as a list of potential risks and threats, " +
		"which should be individually reviewed and reduced by removing false positives. For the remaining risks it " +
		"should be checked in the design and implementation of " + quoted(view.Title) + " whether the mitigation " +
		"advices have been applied or not.")
	what.paragraph("Each risk finding references a chapter of the OWASP ASVS (Application Security Verification " +
		"Standard) audit checklist. The OWASP ASVS checklist should be considered as an inspiration by architects and " +
		"developers to further harden the application in a Defense-in-Depth approach. Additionally, for each risk " +
		"finding a link towards a matching OWASP Cheat Sheet or similar with technical details about how to implement " +
		"a mitigation is given.")
	what.paragraph("In total " + strong(plural(view.Summary.TotalRisks, "initial risk", "initial risks")) + " in " +
		strong(plural(view.Summary.CategoryCount, "category", "categories")) +
		" have been identified during the threat modeling process:")

	rows := make([][]string, 0, len(view.Summary.ByStatus))
	for index, status := range view.Summary.ByStatus {
		row := []string{"", "", status.Level.Title, strconv.Itoa(status.Count)}
		if index < len(view.Summary.BySeverity) {
			severity := view.Summary.BySeverity[index]
			row[0], row[1] = severity.Level.Title, strconv.Itoa(severity.Count)
		}
		rows = append(rows, row)
	}
	what.table([]markdownColumn{{columnSeverity, false}, {textRisks, true}, {columnStatus, false}, {textRisks, true}},
		rows...)
	what.markup(view.ManagementSummaryComment)
}

