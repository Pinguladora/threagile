// impactEntries writes risk categories by severity with the first paragraph of a text of each.
func (what *markdownWriter) impactEntries(entries []viewImpactEntry) {
	if len(entries) == 0 {
		what.paragraph(muted("No risks were identified."))
		return
	}
	list := make([]markdownEntry, 0, len(entries))
	for _, entry := range entries {
		list = append(list, markdownEntry{
			term: strong(entry.Severity.Title) + ": " + what.ref(entry.Category) + ": " + markdownText(entry.Summary) +
				", exploitation likelihood is " + muted(markdownText(entry.Likelihood)) + " with " +
				muted(markdownText(entry.Impact)) + " impact",
			text: entry.Text,
		})
	}
	what.entries(list...)
}

func (what *markdownWriter) riskMitigation(view *reportView) {
	what.paragraph("The following table gives a high-level overview of the risk tracking status (including " +
		"mitigated risks):")
	columns := make([]markdownColumn, 0, 2+len(viewStatuses))
	columns = append(columns, markdownColumn{columnSeverity, false}, markdownColumn{textRisks, true})
	for _, status := range viewStatuses {
		columns = append(columns, markdownColumn{status.Title(), true})
	}
	rows := make([][]string, 0, len(view.Mitigation))
	for _, mitigation := range view.Mitigation {
		row := []string{mitigation.Severity.Title, strconv.Itoa(mitigation.Total)}
		for _, count := range mitigation.ByStatus {
			row = append(row, strconv.Itoa(count.Count))
		}
		rows = append(rows, row)
	}
	what.table(columns, rows...)

	if view.Summary.RemainingRisks == 0 {
		what.paragraph("After removal of risks with status " + muted("mitigated") + " and " + muted("false positive") +
			" " + strong("0 remain unmitigated") + ".")
		return
	}
	what.paragraph("After removal of risks with status " + muted("mitigated") + " and " + muted("false positive") +
		" the following " + strong(strconv.Itoa(view.Summary.RemainingRisks)+" remain unmitigated") + ":")
	rows = make([][]string, 0, len(view.Summary.RemainingBySeverity))
	for index, count := range view.Summary.RemainingBySeverity {
		row := []string{count.Level.Title, strconv.Itoa(count.Count), "", ""}
		if index < len(view.Summary.RemainingByFunction) {
			function := view.Summary.RemainingByFunction[index]
			row[2], row[3] = function.Level.Title, strconv.Itoa(function.Count)
		}
		rows = append(rows, row)
	}
	what.table([]markdownColumn{
		{columnSeverity, false},
		{"Unmitigated risks", true},
		{"To be checked by", false},
		{"Unmitigated risks", true},
	}, rows...)
}

func (what *markdownWriter) risksBySeverity(view *reportView) {
	what.paragraph("All " + strong(plural(view.Summary.TotalRisks, "risk", "risks")) + " by severity, with their " +
		"tracking status. Each risk links to its details in the chapter of its category.")
	for _, severity := range view.RisksBySeverity {
		what.heading(3, "", severity.Severity.Title)
		what.paragraph(strong(plural(len(severity.Risks), "risk", "risks")))
		if len(severity.Risks) == 0 {
			what.paragraph(muted("No risks."))
			continue
		}
		rows := make([][]string, 0, len(severity.Risks))
		for _, risk := range severity.Risks {
			rows = append(rows, []string{
				risk.Severity.Title, what.riskLink(risk), what.ref(risk.Category),
				what.refs(risk.Targets), risk.Status.Title,
			})
		}
		what.table([]markdownColumn{
			{columnSeverity, false},
			{textRisk, false},
			{"Category", false},
			{"Most relevant", false},
			{columnStatus, false},
		}, rows...)
	}
}

func (what *markdownWriter) applicationOverview(view *reportView) {
	what.heading(3, "", "Business Criticality")
	what.paragraph("The overall business criticality of " + quoted(view.Title) + " was rated as:")
	choices := make([]string, 0, len(view.BusinessCriticality))
	for _, choice := range view.BusinessCriticality {
		if choice.Selected {
			choices = append(choices, strong(markdownText(choice.Title))+" (selected)")
		} else {
			choices = append(choices, markdownText(choice.Title))
		}
	}
	what.list(choices...)
	if view.BusinessOverview != nil {
		what.heading(3, "", "Business Overview")
		what.markup(*view.BusinessOverview)
	}
	if view.TechnicalOverview != nil {
		what.heading(3, "", "Technical Overview")
		what.markup(*view.TechnicalOverview)
	}
}

func (what *markdownWriter) assetRegister(view *reportView) {
	what.heading(3, "", "Technical Assets")
	assets := make([]markdownEntry, 0, len(view.TechnicalAssets))
	for _, asset := range view.TechnicalAssets {
		term := what.linked(markdownText(asset.Asset.Title), asset.Anchor)
		if asset.Asset.OutOfScope {
			term += " (" + viewOutOfScopeText + ")"
		}
		assets = append(assets, markdownEntry{term, asset.Description})
	}
	what.entries(assets...)
	what.heading(3, "", "Data Assets")
	dataAssets := make([]markdownEntry, 0, len(view.DataAssets))
	for _, asset := range view.DataAssets {
		dataAssets = append(dataAssets, markdownEntry{
			what.linked(markdownText(asset.Asset.Title), asset.Anchor),
			asset.Description,
		})
	}
	what.entries(dataAssets...)
}

